CREATE TABLE device (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name VARCHAR(255),
                        type VARCHAR(50),
                        location VARCHAR(255),
                        user_id BIGINT,
                        CONSTRAINT fk_device_user
                            FOREIGN KEY (user_id)
                                REFERENCES "user" (id)
                                ON DELETE CASCADE
);

CREATE INDEX idx_device_user_id ON device(user_id);